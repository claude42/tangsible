package eeinit

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

// Inputs is everything Draft needs; all of it already gathered.
type Inputs struct {
	// Playbook is named in the header comment.
	Playbook string
	Base     string
	// BaseIsDefault says Base was nobody's choice (DefaultBaseImage).
	BaseIsDefault bool
	Facts         BaseFacts
	// Needed are the collections the playbook uses (Resolve).
	Needed []Needed
	// Todos are the items that couldn't be resolved.
	Todos []Todo
	// Requirements is the project's requirements.yml, nil if it has none;
	// RequirementsPath names it.
	Requirements     *Requirements
	RequirementsPath string
	// Installed maps a collection to its version on this host.
	Installed map[string]string

	// Binaries are the binaries that controller-side command/shell tasks run
	// and the base image lacks. ResolvePackages says --resolve-packages was
	// given; PackagesFailed is why the lookup could not be done ("" if it
	// could). TemplatedCommands counts controller-side commands whose binary
	// can't be determined.
	Binaries          []BinaryNeed
	ResolvePackages   bool
	PackagesFailed    string
	TemplatedCommands int
}

// BinaryNeed is a missing binary, where it is used and, once looked up, the
// packages that provide it (none: nothing found).
type BinaryNeed struct {
	Name     string
	Locs     []string
	Packages []string
}

// Report summarizes a draft for the end-of-run message.
type Report struct {
	Collections int
	Pinned      int // from the host (the rest came from requirements.yml or are unpinned)
	Todos       int
	Binaries    int // controller-side binaries missing from the base image
}

// maxLocs is how many locations a comment names for one item.
const maxLocs = 2

// Draft renders the execution-environment.yml.
func Draft(in Inputs) (string, Report) {
	var rep Report
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	todo := func(indent, format string, a ...any) {
		rep.Todos++
		w(indent+"# TODO: "+format, a...)
	}

	w("---")
	w("# Draft generated by tangsible ee init from %s. Review it before building:", in.Playbook)
	w("# it names what could be found statically, and marks the rest with TODO.")
	if in.BaseIsDefault {
		w("# The base image is tangsible's built-in default, not your choice: pass --base or")
		w("# set base_image under [execution_environment] to use another.")
	}
	w("# Collection versions come from requirements.yml where it lists them, otherwise")
	w("# from the collections installed on this host; keep or change them.")
	w("version: 3")
	w("")
	w("images:")
	w("  base_image:")
	w("    name: %s", scalar(in.Base))

	// dependencies: always has galaxy, so the key is never null (which
	// ansible-builder rejects) and a commented stanza below it can be
	// uncommented as it is.
	var deps strings.Builder
	dw := func(format string, a ...any) { fmt.Fprintf(&deps, format+"\n", a...) }
	dtodo := func(format string, a ...any) {
		rep.Todos++
		dw("  # TODO: "+format, a...)
	}
	f := in.Facts
	switch {
	case f.Python == "":
		dtodo("no python3 found in the base image (ansible-builder needs one)")
	case f.AnsibleCore != "":
		dw("  # The base image has Python %s (%s) and ansible-core %s.", orUnknown(f.PythonVersion), f.Python, f.AnsibleCore)
	default:
		dw("  # The base image has Python %s (%s).", orUnknown(f.PythonVersion), f.Python)
	}
	if f.Python != "" && !f.Pip {
		dtodo("no pip found for %s in the base image", f.Python)
	}
	if f.Python != "" && f.AnsibleCore == "" {
		dtodo("the base image has no ansible-core: uncomment ansible_core and ansible_runner below")
	}
	intro, body := stanza(f)
	for _, line := range intro {
		dw("  # %s", line)
	}
	dw("")
	for _, line := range body {
		dw("  # %s", line)
	}
	dw("")

	binaryBlock(in, &rep, func(line string) {
		if line == "" {
			dw("")
			return
		}
		dw("  # %s", line)
	})

	collections := mergeCollections(in, &rep)
	if len(collections) == 0 && in.Requirements == nil {
		dw("  # No collections beyond ansible-core's own were found.")
	}
	dw("  galaxy:")
	if len(collections) == 0 {
		dw("    collections: []")
	} else {
		dw("    collections:")
		for _, c := range collections {
			if c.comment != "" {
				dw("      # %s", c.comment)
			}
			if c.note != "" {
				dw("      # %s", c.note)
			}
			deps.WriteString(entry(c.node, "      "))
		}
	}
	if in.Requirements != nil && len(in.Requirements.Roles) > 0 {
		dw("    roles:")
		for _, r := range in.Requirements.Roles {
			deps.WriteString(entry(r, "      "))
		}
	}
	if len(in.Todos) > 0 || in.TemplatedCommands > 0 {
		dw("")
		dw("  # Items the scan couldn't place:")
		todos := append([]Todo(nil), in.Todos...)
		sort.SliceStable(todos, func(i, j int) bool { return locLess(todos[i].Loc, todos[j].Loc) })
		templated := 0
		for _, t := range todos {
			if t.TemplatedInclude {
				templated++
				continue
			}
			dtodo("%s: %s", t.Loc, t.What)
		}
		// Dozens of these are common: one general comment, no locations.
		if templated > 0 {
			dtodo("include/import with a templated target (detected %d in all): what they load can't be determined statically", templated)
		}
		if in.TemplatedCommands > 0 {
			dtodo("command/shell on the controller with a binary that can't be determined statically (detected %d in all)", in.TemplatedCommands)
		}
	}
	w("")
	w("dependencies:")
	b.WriteString(deps.String())

	// options
	w("")
	w("options:")
	if f.PackageManager != "" {
		w("  package_manager_path: %s", scalar(f.PackageManager))
	} else {
		todo("  ", "couldn't tell the base image's package manager: set package_manager_path")
	}
	return b.String(), rep
}

type mergedCollection struct {
	node    *yaml.Node
	comment string // where it comes from
	note    string // a warning about its version
}

// mergeCollections combines requirements.yml's entries (in their order,
// kept as written) with the detected collections they don't list (added,
// sorted), pinning a version from the host where there is none.
func mergeCollections(in Inputs, rep *Report) []mergedCollection {
	needed := map[string]Needed{}
	for _, n := range in.Needed {
		needed[n.Collection] = n
	}
	var out []mergedCollection
	listed := map[string]bool{}
	if in.Requirements != nil {
		for _, rc := range in.Requirements.Collections {
			listed[rc.Name] = true
			m := mergedCollection{node: rc.Node, comment: in.RequirementsPath}
			if n, ok := needed[rc.Name]; ok {
				m.comment += "; used by " + describe(n)
			}
			if rc.Plain && rc.Version == "" {
				m.node, m.note = pin(rc.Name, in.Installed, rep)
			}
			out = append(out, m)
		}
	}
	for _, n := range in.Needed {
		if listed[n.Collection] {
			continue
		}
		node, note := pin(n.Collection, in.Installed, rep)
		out = append(out, mergedCollection{node: node, comment: "detected: " + describe(n), note: note})
	}
	rep.Collections = len(out)
	return out
}

// pin builds a name/version entry for coll, with the host's installed
// version if there is one; otherwise it is unpinned and the note says why.
func pin(coll string, installed map[string]string, rep *Report) (*yaml.Node, string) {
	node := withName(coll, nil)
	if v := installed[coll]; v != "" {
		node.Content = append(node.Content, str("version"), str(v))
		rep.Pinned++
		return node, ""
	}
	return node, "unpinned: not installed on this host"
}

func withName(coll string, n *yaml.Node) *yaml.Node {
	if n != nil && n.Kind == yaml.MappingNode && value(n, "name") != nil {
		return n
	}
	return &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map", Content: []*yaml.Node{str("name"), str(coll)}}
}

func str(s string) *yaml.Node { return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: s} }

// describe is "docker_container (site.yml:14), role x" with at most
// maxLocs locations per item.
func describe(n Needed) string {
	var parts []string
	for _, it := range n.Items {
		s := it.Label
		if len(it.Locs) > 0 {
			s += " (" + locsText(it.Locs) + ")"
		}
		parts = append(parts, s)
	}
	return strings.Join(parts, ", ")
}

// scalar renders s as a YAML scalar, quoted only if it must be.
func scalar(s string) string {
	out, err := yaml.Marshal(s)
	if err != nil {
		return s
	}
	return strings.TrimRight(string(out), "\n")
}

// entry renders one list entry ("- name: x\n  version: y\n") at indent.
func entry(n *yaml.Node, indent string) string {
	var buf strings.Builder
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	_ = enc.Encode(&yaml.Node{Kind: yaml.SequenceNode, Tag: "!!seq", Content: []*yaml.Node{n}})
	_ = enc.Close()
	var out strings.Builder
	for _, line := range strings.Split(strings.TrimRight(buf.String(), "\n"), "\n") {
		out.WriteString(indent + line + "\n")
	}
	return out.String()
}

// locLess orders "path:line" locations by path, then numerically by line.
func locLess(a, b string) bool {
	pa, la := splitLoc(a)
	pb, lb := splitLoc(b)
	if pa != pb {
		return pa < pb
	}
	return la < lb
}

func splitLoc(loc string) (string, int) {
	i := strings.LastIndex(loc, ":")
	if i < 0 {
		return loc, 0
	}
	n, _ := strconv.Atoi(loc[i+1:])
	return loc[:i], n
}

func orUnknown(v string) string {
	if v == "" {
		return "(version unknown)"
	}
	return v
}

// stanza is the commented-out part of dependencies the user can uncomment
// to change the interpreter or ansible, filled in with what the base image
// has: intro explains it, body is the part to uncomment (the draft puts a
// blank line between them). The interpreter's real path and owning package come from the probe
// (the package from the image's own package database); a package it couldn't
// find is replaced by the usual rpm name for the version (python3.14), which
// other distributions may not share, and the note says so.
func stanza(f BaseFacts) (intro, body []string) {
	py := "python3"
	if parts := strings.Split(f.PythonVersion, "."); len(parts) >= 2 {
		py = "python" + parts[0] + "." + parts[1]
	}
	pkg, path := py, "/usr/bin/"+py
	if f.PythonReal != "" {
		path = f.PythonReal
	}
	if f.PythonPackage != "" {
		pkg = f.PythonPackage
	}
	core := "ansible-core"
	if f.AnsibleCore != "" {
		core += "==" + f.AnsibleCore
	}
	note := "the base image's; package_system is a guess at the distribution's package name, adjust it):"
	if f.PythonPackage != "" {
		note = "the base image's; package_system is the package that owns it in the base image):"
	}
	introLine := "To change them, uncomment (python_interpreter installs that Python on top of"
	if f.Python == "" {
		introLine = "To add them, uncomment (python_interpreter installs that Python;"
		note = "package_system is a guess at the distribution's package name, adjust it):"
	}
	return []string{introLine, note}, []string{
		"python_interpreter:",
		"  package_system: " + pkg,
		"  python_path: " + path,
		"ansible_core:",
		"  package_pip: " + core,
		"ansible_runner:",
		"  package_pip: ansible-runner",
	}
}

// locsText is "a.yml:1, b.yml:2, +3 more": at most maxLocs locations.
func locsText(locs []string) string {
	shown := locs
	if len(shown) > maxLocs {
		shown = shown[:maxLocs]
	}
	out := strings.Join(shown, ", ")
	if extra := len(locs) - len(shown); extra > 0 {
		out += fmt.Sprintf(", +%d more", extra)
	}
	return out
}

// binaryBlock writes the comment block about controller-side binaries the
// base image lacks (nothing when there are none), one line per call of line.
// Without package lookup it only lists them; with it, it offers a system:
// stanza to uncomment (bindep syntax) and a TODO for each binary without
// exactly one provider. Nothing is ever uncommented for the user. An empty
// line from line means a blank line; one is also written after the block.
func binaryBlock(in Inputs, rep *Report, line func(string)) {
	if len(in.Binaries) == 0 {
		return
	}
	rep.Binaries = len(in.Binaries)
	line("Binaries used by tasks that run on the controller and missing from the base image")
	line("(only tasks detected as running there count; a role's task file has no play context):")
	resolved := in.ResolvePackages && in.PackagesFailed == ""
	if !resolved {
		for _, b := range in.Binaries {
			line(fmt.Sprintf("  %s: %s", b.Name, locsText(b.Locs)))
		}
		if in.PackagesFailed != "" {
			rep.Todos++
			line("TODO: couldn't look up their packages: " + in.PackagesFailed)
		} else {
			line("Look up their packages with --resolve-packages.")
		}
		line("")
		return
	}
	selector := ""
	switch in.Facts.Family() {
	case "rpm":
		selector = " [platform:rpm]"
	case "dpkg":
		selector = " [platform:dpkg]"
	}
	byPackage := map[string][]string{}
	var packages []string
	var todos []string
	for _, b := range in.Binaries {
		label := b.Name + ": " + locsText(b.Locs)
		switch len(b.Packages) {
		case 0:
			todos = append(todos, fmt.Sprintf("TODO: %q: no package found", b.Name))
		case 1:
			if _, seen := byPackage[b.Packages[0]]; !seen {
				packages = append(packages, b.Packages[0])
			}
			byPackage[b.Packages[0]] = append(byPackage[b.Packages[0]], label)
		default:
			todos = append(todos, fmt.Sprintf("TODO: %q: one of %s (%s)", b.Name, strings.Join(b.Packages, ", "), locsText(b.Locs)))
		}
	}
	sort.Strings(packages)
	if len(packages) > 0 {
		line("To install them, uncomment:")
		line("")
		line("system:")
		for _, p := range packages {
			line(fmt.Sprintf("  - %s%s   # %s", p, selector, strings.Join(byPackage[p], "; ")))
		}
	}
	for _, t := range todos {
		rep.Todos++
		line("  # " + t)
	}
	line("")
}
