package eeinit

import (
	"fmt"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

// Inputs is everything Draft needs; all of it already gathered.
type Inputs struct {
	// Playbook is named in the header comment.
	Playbook string
	Base     string
	// BaseIsDefault says Base was nobody's choice (DefaultBaseImage).
	BaseIsDefault bool
	Facts         BaseFacts
	// Needed are the collections the playbook uses (Resolve).
	Needed []Needed
	// Todos are the items that couldn't be resolved.
	Todos []Todo
	// Requirements is the project's requirements.yml, nil if it has none;
	// RequirementsPath names it.
	Requirements     *Requirements
	RequirementsPath string
	// Installed maps a collection to its version on this host.
	Installed map[string]string
	// Galaxy is what Galaxy said about the collections that were asked
	// (PinTargets), by collection; Latest says --latest was given, so its
	// version wins over the host's.
	Galaxy map[string]GalaxyInfo
	Latest bool
	// ImageTag is the name suggested for the built image in the commented
	// tags: stanza ("" means "my-ee:latest").
	ImageTag string

	// Binaries are the binaries that controller-side command/shell tasks run
	// and the base image lacks. ResolvePackages says --resolve-packages was
	// given; PackagesFailed is why the lookup could not be done ("" if it
	// could). TemplatedCommands counts controller-side commands whose binary
	// can't be determined.
	Binaries          []BinaryNeed
	ResolvePackages   bool
	PackagesFailed    string
	TemplatedCommands int

	// Implied are the packages the rules ask for (ImpliedPackages);
	// TemplatedLookups counts lookup() calls whose plugin name can't be
	// determined.
	Implied          Implied
	TemplatedLookups int
}

// BinaryNeed is a missing binary, where it is used and, once looked up, the
// packages that provide it (none: nothing found).
type BinaryNeed struct {
	Name     string
	Locs     []string
	Packages []string
}

// Report summarizes a draft for the end-of-run message.
type Report struct {
	Collections int
	Pinned      int // from the host (the rest came from requirements.yml, Galaxy or are unpinned)
	FromGalaxy  int // pinned to a version Galaxy named
	Deprecated  int // flagged deprecated on Galaxy
	Todos       int
	Binaries    int // controller-side binaries missing from the base image
	Implied     int // packages the rules ask for
}

// maxLocs is how many locations a comment names for one item.
const maxLocs = 2

// Draft renders the execution-environment.yml.
func Draft(in Inputs) (string, Report) {
	var rep Report
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	todo := func(indent, format string, a ...any) {
		rep.Todos++
		w(indent+"# TODO: "+format, a...)
	}

	w("---")
	w("# Draft generated by tangsible ee init from %s. Review it before building:", in.Playbook)
	w("# it names what could be found statically, and marks the rest with TODO.")
	if in.BaseIsDefault {
		w("# The base image is tangsible's built-in default, not your choice: pass --base or")
		w("# set base_image under [execution_environment] to use another.")
	}
	w("# Collection versions come from requirements.yml where it lists them, otherwise")
	w("# from the collections installed on this host or, where marked, from Galaxy;")
	w("# keep or change them.")
	w("version: 3")
	w("")
	w("images:")
	w("  base_image:")
	w("    name: %s", scalar(in.Base))

	// dependencies: always has galaxy, so the key is never null (which
	// ansible-builder rejects) and a commented stanza below it can be
	// uncommented as it is.
	var deps strings.Builder
	dw := func(format string, a ...any) { fmt.Fprintf(&deps, format+"\n", a...) }
	dtodo := func(format string, a ...any) {
		rep.Todos++
		dw("  # TODO: "+format, a...)
	}
	f := in.Facts
	switch {
	case f.Python == "":
		dtodo("no python3 found in the base image (ansible-builder needs one)")
	case f.AnsibleCore != "":
		dw("  # The base image has Python %s (%s) and ansible-core %s.", orUnknown(f.PythonVersion), f.Python, f.AnsibleCore)
	default:
		dw("  # The base image has Python %s (%s).", orUnknown(f.PythonVersion), f.Python)
	}
	if f.Python != "" && !f.Pip {
		dtodo("no pip found for %s in the base image", f.Python)
	}
	if f.Python != "" && f.AnsibleCore == "" {
		dtodo("the base image has no ansible-core: uncomment ansible_core and ansible_runner below")
	}
	intro, body := stanza(f)
	for _, line := range intro {
		dw("  # %s", line)
	}
	dw("")
	for _, line := range body {
		dw("  # %s", line)
	}
	dw("")

	// Binaries and implied packages: what can't be offered as a package is
	// listed, the rest goes into one python:/system: stanza.
	list, binSystem, binTodos := binaryPlan(in, &rep)
	for _, l := range list {
		dw("  # %s", l)
	}
	if len(list) > 0 {
		dw("")
	}
	rep.Implied = len(in.Implied.Pip) + len(in.Implied.System)
	system := mergeEntries(append(binSystem, in.Implied.System...))
	python := mergeEntries(in.Implied.Pip)
	switch {
	case len(python)+len(system) > 0:
		dw("  # Packages that lookups, controller-side modules and binaries used by the playbook need,")
		dw("  # which their collections or the base image don't provide. To install them, uncomment:")
		dw("")
		for _, group := range []struct {
			key     string
			entries []StanzaEntry
		}{{"python", python}, {"system", system}} {
			if len(group.entries) == 0 {
				continue
			}
			dw("  # %s:", group.key)
			for _, e := range group.entries {
				dw("  #   - %s   # %s", e.Package, e.Comment)
			}
		}
		for _, t := range binTodos {
			rep.Todos++
			dw("  #   # TODO: %s", t)
		}
		dw("")
	case len(binTodos) > 0:
		for _, t := range binTodos {
			rep.Todos++
			dw("  # TODO: %s", t)
		}
		dw("")
	}

	collections := mergeCollections(in, &rep)
	if len(collections) == 0 && in.Requirements == nil {
		dw("  # No collections beyond ansible-core's own were found.")
	}
	dw("  galaxy:")
	if len(collections) == 0 {
		dw("    collections: []")
	} else {
		dw("    collections:")
		for _, c := range collections {
			if c.comment != "" {
				dw("      # %s", c.comment)
			}
			for _, h := range c.hints {
				dw("      # documented requirements of %s", h)
			}
			for _, n := range c.notes {
				dw("      # %s", n)
			}
			deps.WriteString(entry(c.node, "      "))
		}
	}
	if in.Requirements != nil && len(in.Requirements.Roles) > 0 {
		dw("    roles:")
		for _, r := range in.Requirements.Roles {
			deps.WriteString(entry(r, "      "))
		}
	}
	if len(in.Todos) > 0 || in.TemplatedCommands > 0 || in.TemplatedLookups > 0 {
		dw("")
		dw("  # Items the scan couldn't place:")
		todos := append([]Todo(nil), in.Todos...)
		sort.SliceStable(todos, func(i, j int) bool { return locLess(todos[i].Loc, todos[j].Loc) })
		templated := 0
		for _, t := range todos {
			if t.TemplatedInclude {
				templated++
				continue
			}
			dtodo("%s: %s", t.Loc, t.What)
		}
		// Dozens of these are common: one general comment, no locations.
		if templated > 0 {
			dtodo("include/import with a templated target (detected %d in all): what they load can't be determined statically", templated)
		}
		if in.TemplatedCommands > 0 {
			dtodo("command/shell on the controller with a binary that can't be determined statically (detected %d in all)", in.TemplatedCommands)
		}
		if in.TemplatedLookups > 0 {
			dtodo("lookup() with a plugin name that can't be determined statically (detected %d in all)", in.TemplatedLookups)
		}
	}
	w("")
	w("dependencies:")
	b.WriteString(deps.String())

	// options
	w("")
	w("options:")
	if f.PackageManager != "" {
		w("  package_manager_path: %s", scalar(f.PackageManager))
	} else {
		// ansible-builder's own default, written out so options is not null
		// (which it rejects)
		todo("  ", "couldn't tell the base image's package manager: this is ansible-builder's default, set the right one")
		w("  package_manager_path: /usr/bin/dnf")
	}
	tag := in.ImageTag
	if tag == "" {
		tag = "my-ee:latest"
	}
	w("")
	w("  # The names the built image gets (ansible-builder build --tag overrides them).")
	w("  # To set them, uncomment and adjust:")
	w("")
	w("  # tags:")
	w("  #   - %s", scalar(tag))
	return b.String(), rep
}

type mergedCollection struct {
	node    *yaml.Node
	comment string   // where it comes from
	hints   []string // documented requirements of what uses it
	notes   []string // where its version comes from, or why it has none
}

// mergeCollections combines requirements.yml's entries (in their order,
// kept as written) with the detected collections they don't list (added,
// sorted), pinning a version from the host where there is none.
func mergeCollections(in Inputs, rep *Report) []mergedCollection {
	needed := map[string]Needed{}
	for _, n := range in.Needed {
		needed[n.Collection] = n
	}
	var out []mergedCollection
	listed := map[string]bool{}
	if in.Requirements != nil {
		for _, rc := range in.Requirements.Collections {
			listed[rc.Name] = true
			m := mergedCollection{node: rc.Node, comment: in.RequirementsPath}
			if n, ok := needed[rc.Name]; ok {
				m.comment += "; used by " + describe(n)
				m.hints = n.Hints
			}
			if rc.Plain && rc.Version == "" {
				m.node, m.notes = pin(rc.Name, in, rep)
			}
			out = append(out, m)
		}
	}
	for _, n := range in.Needed {
		if listed[n.Collection] {
			continue
		}
		node, notes := pin(n.Collection, in, rep)
		out = append(out, mergedCollection{node: node, comment: "detected: " + describe(n), hints: n.Hints, notes: notes})
	}
	rep.Collections = len(out)
	return out
}

// pin builds a name/version entry for coll and the notes that say where the
// version comes from (or why there is none). The order: the host's installed
// version, unless --latest and Galaxy named one; otherwise Galaxy's; otherwise
// unpinned. A collection Galaxy flags deprecated says so.
func pin(coll string, in Inputs, rep *Report) (*yaml.Node, []string) {
	node := withName(coll, nil)
	g := in.Galaxy[coll]
	host := in.Installed[coll]
	var notes []string
	switch {
	case host != "" && !(in.Latest && g.Version != ""):
		node.Content = append(node.Content, str("version"), str(host))
		rep.Pinned++
	case g.Version != "":
		node.Content = append(node.Content, str("version"), str(g.Version))
		rep.FromGalaxy++
		notes = append(notes, g.Note)
	case g.Note != "":
		notes = append(notes, g.Note)
	default:
		notes = append(notes, "unpinned: not installed on this host")
	}
	if g.Deprecated {
		rep.Deprecated++
		notes = append(notes, "deprecated on Galaxy")
	}
	return node, notes
}

// PinTargets are the collections Galaxy is to be asked about: those the draft
// pins itself (a requirements.yml entry without a version, a detected
// collection it doesn't list) that the host lacks, or all of them with
// latest. Sorted, without duplicates.
func PinTargets(in Inputs, latest bool) []string {
	var names []string
	listed := map[string]bool{}
	if in.Requirements != nil {
		for _, rc := range in.Requirements.Collections {
			listed[rc.Name] = true
			if rc.Plain && rc.Version == "" {
				names = append(names, rc.Name)
			}
		}
	}
	for _, n := range in.Needed {
		if !listed[n.Collection] {
			names = append(names, n.Collection)
		}
	}
	sort.Strings(names)
	var out []string
	for i, n := range names {
		if i > 0 && n == names[i-1] {
			continue
		}
		if latest || in.Installed[n] == "" {
			out = append(out, n)
		}
	}
	return out
}

func withName(coll string, n *yaml.Node) *yaml.Node {
	if n != nil && n.Kind == yaml.MappingNode && value(n, "name") != nil {
		return n
	}
	return &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map", Content: []*yaml.Node{str("name"), str(coll)}}
}

func str(s string) *yaml.Node { return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: s} }

// describe is "docker_container (site.yml:14), role x" with at most
// maxLocs locations per item.
func describe(n Needed) string {
	var parts []string
	for _, it := range n.Items {
		s := it.Label
		if len(it.Locs) > 0 {
			s += " (" + locsText(it.Locs) + ")"
		}
		parts = append(parts, s)
	}
	return strings.Join(parts, ", ")
}

// scalar renders s as a YAML scalar, quoted only if it must be.
func scalar(s string) string {
	out, err := yaml.Marshal(s)
	if err != nil {
		return s
	}
	return strings.TrimRight(string(out), "\n")
}

// entry renders one list entry ("- name: x\n  version: y\n") at indent.
func entry(n *yaml.Node, indent string) string {
	var buf strings.Builder
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	_ = enc.Encode(&yaml.Node{Kind: yaml.SequenceNode, Tag: "!!seq", Content: []*yaml.Node{n}})
	_ = enc.Close()
	var out strings.Builder
	for _, line := range strings.Split(strings.TrimRight(buf.String(), "\n"), "\n") {
		out.WriteString(indent + line + "\n")
	}
	return out.String()
}

// locLess orders "path:line" locations by path, then numerically by line.
func locLess(a, b string) bool {
	pa, la := splitLoc(a)
	pb, lb := splitLoc(b)
	if pa != pb {
		return pa < pb
	}
	return la < lb
}

func splitLoc(loc string) (string, int) {
	i := strings.LastIndex(loc, ":")
	if i < 0 {
		return loc, 0
	}
	n, _ := strconv.Atoi(loc[i+1:])
	return loc[:i], n
}

func orUnknown(v string) string {
	if v == "" {
		return "(version unknown)"
	}
	return v
}

// stanza is the commented-out part of dependencies the user can uncomment
// to change the interpreter or ansible, filled in with what the base image
// has: intro explains it, body is the part to uncomment (the draft puts a
// blank line between them). The interpreter's real path and owning package come from the probe
// (the package from the image's own package database); a package it couldn't
// find is replaced by the usual rpm name for the version (python3.14), which
// other distributions may not share, and the note says so.
func stanza(f BaseFacts) (intro, body []string) {
	py := "python3"
	if parts := strings.Split(f.PythonVersion, "."); len(parts) >= 2 {
		py = "python" + parts[0] + "." + parts[1]
	}
	pkg, path := py, "/usr/bin/"+py
	if f.PythonReal != "" {
		path = f.PythonReal
	}
	if f.PythonPackage != "" {
		pkg = f.PythonPackage
	}
	core := "ansible-core"
	if f.AnsibleCore != "" {
		core += "==" + f.AnsibleCore
	}
	note := "the base image's; package_system is a guess at the distribution's package name, adjust it):"
	if f.PythonPackage != "" {
		note = "the base image's; package_system is the package that owns it in the base image):"
	}
	introLine := "To change them, uncomment (python_interpreter installs that Python on top of"
	if f.Python == "" {
		introLine = "To add them, uncomment (python_interpreter installs that Python;"
		note = "package_system is a guess at the distribution's package name, adjust it):"
	}
	return []string{introLine, note}, []string{
		"python_interpreter:",
		"  package_system: " + pkg,
		"  python_path: " + path,
		"ansible_core:",
		"  package_pip: " + core,
		"ansible_runner:",
		"  package_pip: ansible-runner",
	}
}

// locsText is "a.yml:1, b.yml:2, +3 more": at most maxLocs locations.
func locsText(locs []string) string {
	shown := locs
	if len(shown) > maxLocs {
		shown = shown[:maxLocs]
	}
	out := strings.Join(shown, ", ")
	if extra := len(locs) - len(shown); extra > 0 {
		out += fmt.Sprintf(", +%d more", extra)
	}
	return out
}

// binaryPlan decides what to say about the controller-side binaries the base
// image lacks (nothing when there are none). Without a package lookup it
// returns list, the comment lines that name them (no stanza); with one, the
// entries for the system: stanza (bindep syntax, with the platform selector
// of the image's family) and a TODO text for each binary without exactly one
// provider. Nothing is ever uncommented for the user.
func binaryPlan(in Inputs, rep *Report) (list []string, system []StanzaEntry, todos []string) {
	if len(in.Binaries) == 0 {
		return nil, nil, nil
	}
	rep.Binaries = len(in.Binaries)
	resolved := in.ResolvePackages && in.PackagesFailed == ""
	if !resolved {
		list = append(list,
			"Binaries used by tasks that run on the controller and missing from the base image",
			"(only tasks detected as running there count; a role's task file has no play context):")
		for _, b := range in.Binaries {
			list = append(list, fmt.Sprintf("  %s: %s", b.Name, locsText(b.Locs)))
		}
		if in.PackagesFailed != "" {
			rep.Todos++
			list = append(list, "TODO: couldn't look up their packages: "+in.PackagesFailed)
		} else {
			list = append(list, "Look up their packages with --resolve-packages.")
		}
		return list, nil, nil
	}
	selector := ""
	switch in.Facts.Family() {
	case "rpm":
		selector = " [platform:rpm]"
	case "dpkg":
		selector = " [platform:dpkg]"
	}
	for _, b := range in.Binaries {
		switch len(b.Packages) {
		case 0:
			todos = append(todos, fmt.Sprintf("binary %q (%s): no package found", b.Name, locsText(b.Locs)))
		case 1:
			system = append(system, StanzaEntry{b.Packages[0] + selector, b.Name + ": " + locsText(b.Locs)})
		default:
			todos = append(todos, fmt.Sprintf("binary %q (%s): one of %s", b.Name, locsText(b.Locs), strings.Join(b.Packages, ", ")))
		}
	}
	return nil, system, todos
}

// mergeEntries sorts entries by package and joins the comments of those for
// the same package.
func mergeEntries(in []StanzaEntry) []StanzaEntry {
	by := map[string]string{}
	var pkgs []string
	for _, e := range in {
		if c, seen := by[e.Package]; seen {
			by[e.Package] = c + "; " + e.Comment
			continue
		}
		by[e.Package] = e.Comment
		pkgs = append(pkgs, e.Package)
	}
	sort.Strings(pkgs)
	out := make([]StanzaEntry, len(pkgs))
	for i, p := range pkgs {
		out[i] = StanzaEntry{p, by[p]}
	}
	return out
}

// SuggestTag is the image name suggested for a project in dir: its name,
// made a valid image name, with "-ee:latest".
func SuggestTag(dir string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(filepath.Base(dir)) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '.', r == '_', r == '-':
			b.WriteRune(r)
		default:
			b.WriteByte('-')
		}
	}
	name := strings.Trim(b.String(), "-._")
	if name == "" {
		name = "my"
	}
	return name + "-ee:latest"
}
