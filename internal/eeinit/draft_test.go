func TestDraftStanzaCanBeUncommented(t *testing.T) {
	got, _ := Draft(Inputs{Playbook: "site.yml", Base: "img:1", Facts: microFacts})
	var lines []string
	for _, l := range strings.Split(got, "\n") {
		for _, key := range []string{"python_interpreter:", "package_system:", "python_path:", "ansible_core:", "package_pip:", "ansible_runner:"} {
			if strings.Contains(l, "# "+key) || strings.Contains(l, "#   "+key) {
				l = strings.Replace(l, "# ", "", 1)
			}
		}
		lines = append(lines, l)
	}
	var v struct {
		Dependencies map[string]map[string]any `yaml:"dependencies"`
	}
	if err := yaml.Unmarshal([]byte(strings.Join(lines, "\n")), &v); err != nil {
		t.Fatalf("not valid after uncommenting: %v", err)
	}
	d := v.Dependencies
	if d["python_interpreter"]["package_system"] != "python3" || d["python_interpreter"]["python_path"] != "/usr/bin/python3.14" ||
		d["ansible_core"]["package_pip"] != "ansible-core==2.21.5" || d["ansible_runner"]["package_pip"] != "ansible-runner" {
		t.Errorf("uncommented dependencies = %+v", d)
	}
}

