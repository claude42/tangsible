var microFacts = BaseFacts{PackageManager: "/usr/bin/microdnf", Python: "/usr/bin/python3", PythonReal: "/usr/bin/python3.14", PythonPackage: "python3", PythonVersion: "3.14.8", Pip: true, AnsibleCore: "2.21.5"}

func TestDraftDetectedCollections(t *testing.T) {
	got, rep := Draft(Inputs{
		Playbook: "site.yml", Base: "img:1", BaseIsDefault: true, Facts: microFacts,
		Needed: []Needed{
			{"community.docker", []Item{{"docker_container", []string{"site.yml:5", "a.yml:2", "a.yml:9"}}}},
			{"x.y", []Item{{"role x.y.web", nil}}},
		},
		Todos:     []Todo{{Loc: "site.yml:13", What: "later"}, {Loc: "site.yml:4", What: "earlier"}},
		Installed: map[string]string{"community.docker": "4.7.0"},
	})
	want := `---
# Draft generated by tangsible ee init from site.yml. Review it before building:
# it names what could be found statically, and marks the rest with TODO.
# The base image is tangsible's built-in default, not your choice: pass --base or
# set base_image under [execution_environment] to use another.
# Collection versions come from requirements.yml where it lists them, otherwise
# from the collections installed on this host; keep or change them.
version: 3

images:
  base_image:
    name: img:1

dependencies:
  # The base image has Python 3.14.8 (/usr/bin/python3) and ansible-core 2.21.5.
  # To change them, uncomment (python_interpreter installs that Python on top of
  # the base image's; package_system is the package that owns it in the base image):

  # python_interpreter:
  #   package_system: python3
  #   python_path: /usr/bin/python3.14
  # ansible_core:
  #   package_pip: ansible-core==2.21.5
  # ansible_runner:
  #   package_pip: ansible-runner

  galaxy:
    collections:
      # detected: docker_container (site.yml:5, a.yml:2, +1 more)
      - name: community.docker
        version: 4.7.0
      # detected: role x.y.web
      # unpinned: not installed on this host
      - name: x.y

  # Items the scan couldn't place:
  # TODO: site.yml:4: earlier
  # TODO: site.yml:13: later

options:
  package_manager_path: /usr/bin/microdnf
`
	if got != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
	if rep != (Report{Collections: 2, Pinned: 1, Todos: 2}) {
		t.Errorf("report = %+v", rep)
	}
	assertValidYAML(t, got)
}

func TestDraftRequirements(t *testing.T) {
	req, err := ParseRequirements([]byte(`collections:
  - community.general
  - name: community.docker
    version: ">=3.0.0"
  - name: ns.pinned
    version: 1.2.3
    source: https://hub.example.com
roles:
  - src: geerlingguy.nginx
`))
	if err != nil {
		t.Fatal(err)
	}
	got, rep := Draft(Inputs{
		Playbook: "site.yml", Base: "img:1", Facts: microFacts,
		Needed: []Needed{
			{"community.docker", []Item{{"docker_container", []string{"site.yml:5"}}}},
			{"other.coll", []Item{{"m", []string{"site.yml:9"}}}},
		},
		Requirements: req, RequirementsPath: "requirements.yml",
		Installed: map[string]string{"community.docker": "9.9.9", "community.general": "11.2.1", "other.coll": "1.0.0"},
	})
	for _, want := range []string{
		// listed without a version: pinned from the host
		"      # requirements.yml\n      - name: community.general\n        version: 11.2.1\n",
		// the requirements version wins over the host's
		"      # requirements.yml; used by docker_container (site.yml:5)\n      - name: community.docker\n        version: \">=3.0.0\"\n",
		// kept as written
		"      - name: ns.pinned\n        version: 1.2.3\n        source: https://hub.example.com\n",
		// a detected one it doesn't list is added
		"      # detected: m (site.yml:9)\n      - name: other.coll\n        version: 1.0.0\n",
		"    roles:\n      - src: geerlingguy.nginx\n",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %q in:\n%s", want, got)
		}
	}
	if strings.Contains(got, "built-in default") {
		t.Errorf("a chosen base must not be called the default:\n%s", got)
	}
	if rep.Collections != 4 || rep.Pinned != 2 {
		t.Errorf("report = %+v", rep)
	}
	assertValidYAML(t, got)
}

